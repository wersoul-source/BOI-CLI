func Render8Art(text string) []string {
	lines := make([]string, 7)
	for _, ch := range text {
		u := ch
		if u >= 'a' && u <= 'z' {
			u = u - 'a' + 'A'
		}
		glyph, ok := Font8x7[u]
		if !ok {
			glyph = Font8x7[' ']
		}
		for i := 0; i < 7; i++ {
			if i < len(glyph) {
				lines[i] += glyph[i] + "  "
			}
		}
	}
	for i := 0; i < 7; i++ {
		end := len(lines[i])
		for end > 0 && lines[i][end-1] == ' ' {
			end--
		}
		lines[i] = lines[i][:end]
	}
	return lines
}

func Render8ArtFramed(text string) string {
	lines := Render8Art(text)

	maxWidth := 0
	for _, line := range lines {
		if len(line) > maxWidth {
			maxWidth = len(line)
		}
	}

	var result string
	result += "╔"
	for i := 0; i < maxWidth; i++ {
		result += "═"
	}
	result += "╗\n"

	for _, line := range lines {
		padding := maxWidth - len(line)
		result += "║" + line
		for i := 0; i < padding; i++ {
			result += " "
		}
		result += "║\n"
	}

	result += "╚"
	for i := 0; i < maxWidth; i++ {
		result += "═"
	}
	result += "╝\n"

	return result
}
